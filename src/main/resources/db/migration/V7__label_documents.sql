CREATE TABLE label_document (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 dataset_id BIGINT REFERENCES dataset(id),
 source_job_id BIGINT UNIQUE REFERENCES auto_label_job(id),
 source_type VARCHAR(32) NOT NULL CHECK (source_type IN ('UPLOAD','AUTO_LABEL')),
 original_text TEXT NOT NULL,
 head_revision INTEGER NOT NULL DEFAULT 0 CHECK (head_revision >= 0),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE label_revision (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id BIGINT NOT NULL REFERENCES label_document(id) ON DELETE CASCADE,
 number INTEGER NOT NULL CHECK (number >= 0),
 payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL,
 UNIQUE(document_id, number)
);
CREATE INDEX idx_label_document_created ON label_document(created_at DESC);
COMMENT ON TABLE label_revision IS 'Immutable snapshots. Revision 0 is the imported or generated baseline; edits create new revisions.';
