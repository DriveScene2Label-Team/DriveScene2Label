-- Label edits on GT annotations and VESPA predictions (UI renewal: rename / delete / revert / history).
-- Original rows are never modified: gt_annotation, its nuScenes category and predicted_annotation keep their values.
-- label_override holds the current effective state of an edited box; label_edit + label_edit_target are the history
-- (one edit may cover every frame of a GT instance) and keep each target's previous state so an edit can be reverted.

CREATE TABLE label_override (
 target_type TEXT NOT NULL CHECK (target_type IN ('ANNOTATION','PREDICTION')),
 target_id BIGINT NOT NULL,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id) ON DELETE CASCADE,
 -- NULL = class unchanged (only deleted). Stored only when it differs from the original class.
 label TEXT,
 deleted BOOLEAN NOT NULL DEFAULT false,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (target_type, target_id),
 CHECK (label IS NOT NULL OR deleted)
);
CREATE INDEX idx_label_override_dataset ON label_override(dataset_id);

CREATE TABLE label_edit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id) ON DELETE CASCADE,
 scene_id BIGINT NOT NULL REFERENCES scene(id) ON DELETE CASCADE,
 -- PREDICTION edits only: the job whose box was edited.
 job_id BIGINT REFERENCES auto_label_job(id) ON DELETE CASCADE,
 target_type TEXT NOT NULL CHECK (target_type IN ('ANNOTATION','PREDICTION')),
 action TEXT NOT NULL CHECK (action IN ('RENAME','DELETE')),
 scope TEXT NOT NULL CHECK (scope IN ('SAMPLE','INSTANCE')),
 instance_token TEXT,
 from_label TEXT NOT NULL,
 to_label TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reverted_at TIMESTAMPTZ,
 CHECK ((action = 'RENAME') = (to_label IS NOT NULL)),
 CHECK (target_type = 'ANNOTATION' OR (job_id IS NOT NULL AND scope = 'SAMPLE'))
);
CREATE INDEX idx_label_edit_scene ON label_edit(scene_id, id DESC);

CREATE TABLE label_edit_target (
 edit_id BIGINT NOT NULL REFERENCES label_edit(id) ON DELETE CASCADE,
 target_type TEXT NOT NULL CHECK (target_type IN ('ANNOTATION','PREDICTION')),
 target_id BIGINT NOT NULL,
 sample_token VARCHAR(64) NOT NULL,
 -- State of label_override before this edit (prev_label NULL and prev_deleted false = no override row).
 prev_label TEXT,
 prev_deleted BOOLEAN NOT NULL,
 PRIMARY KEY (edit_id, target_id)
);
CREATE INDEX idx_label_edit_target ON label_edit_target(target_type, target_id, edit_id);
